#!/usr/bin/env bash
# ==============================================================================
# WayleThemeSelector - Instantaneous Theme Switcher for Wayle & Hyprland
# High-performance zero-latency architecture for AMD Ryzen 9 9950X / CachyOS
# Bound to: Super + Alt + B
# ==============================================================================
set -euo pipefail

THEMES_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/wayle/themes"
RUNTIME_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/wayle/runtime.toml"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/wayle"
ACTIVE_THEME_FILE="${STATE_DIR}/active_theme"
ROFI_COLORS="${XDG_CONFIG_HOME:-$HOME/.config}/rofi/colors.rasi"

mkdir -p "$STATE_DIR"

if [ ! -d "$THEMES_DIR" ]; then
    notify-send -u critical "Wayle Error" "Diretório de temas não encontrado: $THEMES_DIR"
    exit 1
fi

# Function to apply theme by name
apply_theme() {
    local theme_name="$1"
    local theme_file="${THEMES_DIR}/${theme_name}.toml"

    if [ ! -f "$theme_file" ]; then
        notify-send -u critical "Wayle Error" "Arquivo de tema não encontrado: $theme_file"
        return 1
    fi

    # Read colors and write to runtime.toml and rofi colors.rasi
    python3 -c '
import sys, tomllib, os

theme_path = sys.argv[1]
runtime_path = sys.argv[2]
rofi_colors_path = sys.argv[3]

with open(theme_path, "rb") as f:
    palette = tomllib.load(f)

# Format for Wayle runtime.toml
runtime_content = [
    "# Generated by WayleThemeSelector",
    "[styling.palette]"
]

required_keys = ["bg", "surface", "elevated", "fg", "fg-muted", "primary", "red", "yellow", "green", "blue"]

for k in required_keys:
    val = palette.get(k) or palette.get(k.replace("-", "_")) or "#ffffff"
    runtime_content.append(f"{k} = \"{val}\"")

with open(runtime_path, "w") as f:
    f.write("\n".join(runtime_content) + "\n")

# Format for Rofi colors.rasi
bg = palette.get("bg", "#1e1e2e")
surface = palette.get("surface", "#181825")
elevated = palette.get("elevated", "#313244")
fg = palette.get("fg", "#cdd6f4")
fg_muted = palette.get("fg_muted") or palette.get("fg-muted") or "#a6adc8"
primary = palette.get("primary", "#cba6f7")
red = palette.get("red", "#f38ba8")
green = palette.get("green", "#a6e3a1")
yellow = palette.get("yellow", "#f9e2af")
blue = palette.get("blue", "#89b4fa")

rofi_content = [
    "/* Generated by WayleThemeSelector */",
    "* {",
    f"    bg:           {bg}ff;",
    f"    surface:      {surface}ee;",
    f"    elevated:     {elevated}cc;",
    f"    fg:           {fg}ff;",
    f"    fg-muted:     {fg_muted}aa;",
    f"    primary:      {primary}ff;",
    f"    red:          {red}ff;",
    f"    green:        {green}ff;",
    f"    yellow:       {yellow}ff;",
    f"    blue:         {blue}ff;",
    "}"
]

with open(rofi_colors_path, "w") as f:
    f.write("\n".join(rofi_content) + "\n")
' "$theme_file" "$RUNTIME_CONFIG" "$ROFI_COLORS"

    echo "$theme_name" > "$ACTIVE_THEME_FILE"
    notify-send -u low -a "Wayle" "󰏘 Tema Wayle Aplicado" "Esquema: <b>${theme_name}</b>"
}

# If theme name passed directly as CLI argument, apply immediately
if [ "${1:-}" != "" ]; then
    apply_theme "$1"
    exit 0
fi

# Determine current active theme
current_theme=""
if [ -f "$ACTIVE_THEME_FILE" ]; then
    current_theme=$(cat "$ACTIVE_THEME_FILE")
fi

# Build menu list
options=()
for p in "$THEMES_DIR"/*.toml; do
    name=$(basename "$p" .toml)
    if [ "$name" = "$current_theme" ]; then
        options+=("●  $name (Ativo)")
    else
        options+=("○  $name")
    fi
done

# Launch Rofi dmenu
chosen=$(printf '%s\n' "${options[@]}" | rofi -dmenu -i -p "󰏘 Tema Wayle" || true)

# Exit if cancelled
if [ -z "$chosen" ]; then
    exit 0
fi

# Clean selection name
clean_name=$(echo "$chosen" | sed 's/^[●○][[:space:]]*//; s/[[:space:]]*(Ativo)//; s/^[[:space:]]*//; s/[[:space:]]*$//')

apply_theme "$clean_name"
