#!/usr/bin/env bash
# ==============================================================================
# WayleStyleSelector - Interactive Visual Style Selector for Wayle
# Port of JaKooLit WaybarStyles system to native Wayle SCSS architecture
# Bound to: Super + Alt + B
# ==============================================================================
set -euo pipefail

STYLES_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/wayle/styles"
THEMES_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/wayle/themes"
INDEX_SCSS="${STYLES_DIR}/index.scss"
RUNTIME_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/wayle/runtime.toml"
ROFI_COLORS="${XDG_CONFIG_HOME:-$HOME/.config}/rofi/colors.rasi"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/wayle"
ACTIVE_STYLE_FILE="${STATE_DIR}/active_style"

mkdir -p "$STATE_DIR"

# Style mappings (Display Name -> scss file name, theme palette name)
declare -A STYLE_SCSS=(
    ["Catppuccin-Mocha"]="catppuccin-mocha:Catppuccin-Mocha"
    ["ML4W-Glass-3D"]="ml4w-glass-3d:Crystal-Clear-Glass"
    ["Neon-Circuit-Cyberpunk"]="neon-circuit:Neon-Circuit-Cyberpunk"
    ["Rainbow-RGB-Bordered"]="rainbow-rgb:Colorful-Chroma-Spectrum"
    ["Tokyo-Night"]="tokyo-night:Tokyo-Night"
    ["Nord-Frost"]="nord-frost:Nord-Frost"
    ["Everforest-Natural"]="everforest:Everforest-Natural"
    ["Gruvbox-Retro"]="gruvbox-retro:Gruvbox-Retro"
    ["Black-White-Monochrome"]="monochrome:Black-&-White-Monochrome"
    ["Rose-Pine"]="rose-pine:Rose-Pine"
)

apply_style() {
    local choice="$1"
    local mapping="${STYLE_SCSS[$choice]:-}"

    if [ -z "$mapping" ]; then
        notify-send -u critical "Wayle Error" "Estilo não mapeado: $choice"
        return 1
    fi

    IFS=":" read -r scss_name theme_name <<< "$mapping"

    # 1. Update index.scss with chosen visual style
    cat << EOF > "$INDEX_SCSS"
// ==============================================================================
// JaKooLit Style Entry Point (Wayle)
// Generated by WayleStyleSelector
// ==============================================================================

@import "base";
@import "${scss_name}";
EOF

    # 2. Update runtime.toml and rofi colors.rasi if theme file exists
    local theme_file="${THEMES_DIR}/${theme_name}.toml"
    if [ -f "$theme_file" ]; then
        python3 -c '
import sys, tomllib

theme_path = sys.argv[1]
runtime_path = sys.argv[2]
rofi_colors_path = sys.argv[3]

with open(theme_path, "rb") as f:
    palette = tomllib.load(f)

runtime_content = [
    "# Generated by WayleStyleSelector",
    "[styling.palette]"
]

required_keys = ["bg", "surface", "elevated", "fg", "fg-muted", "primary", "red", "yellow", "green", "blue"]

for k in required_keys:
    val = palette.get(k) or palette.get(k.replace("-", "_")) or "#ffffff"
    runtime_content.append(f"{k} = \"{val}\"")

with open(runtime_path, "w") as f:
    f.write("\n".join(runtime_content) + "\n")

bg = palette.get("bg", "#1e1e2e")
surface = palette.get("surface", "#181825")
elevated = palette.get("elevated", "#313244")
fg = palette.get("fg", "#cdd6f4")
fg_muted = palette.get("fg_muted") or palette.get("fg-muted") or "#a6adc8"
primary = palette.get("primary", "#cba6f7")
red = palette.get("red", "#f38ba8")
green = palette.get("green", "#a6e3a1")
yellow = palette.get("yellow", "#f9e2af")
blue = palette.get("blue", "#89b4fa")

rofi_content = [
    "/* Generated by WayleStyleSelector */",
    "* {",
    f"    bg:           {bg}ff;",
    f"    surface:      {surface}ee;",
    f"    elevated:     {elevated}cc;",
    f"    fg:           {fg}ff;",
    f"    fg-muted:     {fg_muted}aa;",
    f"    primary:      {primary}ff;",
    f"    red:          {red}ff;",
    f"    green:        {green}ff;",
    f"    yellow:       {yellow}ff;",
    f"    blue:         {blue}ff;",
    "}"
]

with open(rofi_colors_path, "w") as f:
    f.write("\n".join(rofi_content) + "\n")
' "$theme_file" "$RUNTIME_CONFIG" "$ROFI_COLORS"
    fi

    echo "$choice" > "$ACTIVE_STYLE_FILE"
    notify-send -u low -a "Wayle" "󰏘 Estilo Visual Aplicado" "Tema: <b>${choice}</b>"
}

# Direct CLI execution
if [ "${1:-}" != "" ]; then
    apply_style "$1"
    exit 0
fi

# Determine current style
current_style=""
if [ -f "$ACTIVE_STYLE_FILE" ]; then
    current_style=$(cat "$ACTIVE_STYLE_FILE")
fi

# Build menu list
options=()
for name in "Catppuccin-Mocha" "ML4W-Glass-3D" "Neon-Circuit-Cyberpunk" "Rainbow-RGB-Bordered" "Tokyo-Night" "Nord-Frost" "Everforest-Natural" "Gruvbox-Retro" "Black-White-Monochrome" "Rose-Pine"; do
    if [ "$name" = "$current_style" ]; then
        options+=("👉  $name (Ativo)")
    else
        options+=("    $name")
    fi
done

# Launch Rofi
chosen=$(printf '%s\n' "${options[@]}" | rofi -dmenu -i -p "󰏘 Estilo de Barra (Super+Alt+B)" || true)

if [ -z "$chosen" ]; then
    exit 0
fi

clean_name=$(echo "$chosen" | sed 's/^[[:space:]]*//; s/^👉[[:space:]]*//; s/[[:space:]]*(Ativo)//; s/[[:space:]]*$//')
apply_style "$clean_name"
